#!/usr/bin/env python3
"""Writes the dmusic tables that are DirectX's own data, from the player's game disc.

The disc's DirectX/DirectX.cab holds the DirectX 9.0b (Dec 2002) DLLs the game ran on. From them:
  _MsFilterTables.h  dmsynth.dll's DLS2 2-pole low-pass coefficients (K, B1, B2, Q30; 16
                     resonance rows by 89 cutoff columns);
  _MsCurveTables.h   dmime.dll's curve shapes (LINEAR, SINE, LOG, EXP; 193 steps of 0..19200).
They are Microsoft's data, so they are read at build time rather than kept in this repository.
Without the disc the filter is left out and every curve shape is linear.

usage: directx_tables.py <out dir> (--iso Battlegrounds.iso | --dir <folder with the DLLs>)
"""
import os
import struct
import subprocess
import sys


def from_iso(iso, name):
    cab = subprocess.run(['bsdtar', '-xOf', iso, 'DirectX/DirectX.cab'], capture_output=True, check=True).stdout
    return subprocess.run(['bsdtar', '-xOf', '-', name], input=cab, capture_output=True, check=True).stdout


def reader(b, image_base):
    pe = struct.unpack_from('<I', b, 0x3c)[0]
    nsec = struct.unpack_from('<H', b, pe + 6)[0]
    optsz = struct.unpack_from('<H', b, pe + 20)[0]
    if struct.unpack_from('<I', b, pe + 24 + 28)[0] != image_base:
        raise ValueError('not the DirectX 9.0b DLL')
    secs = [struct.unpack_from('<IIII', b, pe + 24 + optsz + i * 40 + 8) for i in range(nsec)]

    def read(addr, n):
        rva = addr - image_base
        for vsz, va, rsz, raw in secs:
            if va <= rva < va + max(vsz, rsz):
                return b[raw + rva - va:raw + rva - va + n]
        raise ValueError('address %x not mapped' % addr)
    return read


def filter_tables(b):
    read = reader(b, 0x77480000)
    out = {}
    for name, addr in (('K', 0x774970E0), ('B1', 0x77494460), ('B2', 0x77495AA0)):
        d = read(addr, 16 * 89 * 4)
        out[name] = [struct.unpack_from('<89i', d, r * 89 * 4) for r in range(16)]
    if out['K'][0][0] != 208823:
        raise ValueError('unexpected filter tables')
    return out


def curve_tables(b):
    read = reader(b, 0x77300000)
    out = {}
    for name, addr in (('LINEAR', 0x77328020), ('SINE', 0x773281A8), ('LOG', 0x77328330), ('EXP', 0x773284B8)):
        out[name] = struct.unpack_from('<193h', read(addr, 193 * 2))
    if out['LINEAR'][1] != 100 or out['LINEAR'][192] != 19200:
        raise ValueError('unexpected curve tables')
    return out


def load(mode, src, name):
    return from_iso(src, name) if mode == '--iso' else open(os.path.join(src, name), 'rb').read()


def main():
    out_dir, mode, src = sys.argv[1], sys.argv[2], sys.argv[3]
    os.makedirs(out_dir, exist_ok=True)
    head = '// Generated by re/scripts/directx_tables.py from the game disc\'s %s.\n#pragma once\n#include <stdint.h>\n\n'
    try:
        f = filter_tables(load(mode, src, 'dmsynth.dll'))
    except (OSError, ValueError, subprocess.CalledProcessError, struct.error) as e:
        print('dmsynth.dll: %s; building without the DLS2 filter' % e, file=sys.stderr)
        f = None
    with open(os.path.join(out_dir, '_MsFilterTables.h'), 'w') as o:
        o.write(head % 'dmsynth.dll' + '#define DmMs_FILTER_TABLES %d\n\n' % (1 if f else 0))
        for name in ('K', 'B1', 'B2'):
            o.write('static const int32_t DmMs_FILTER_%s[16][89] = {\n' % name)
            for row in (f[name] if f else [[0] * 89] * 16):
                o.write('\t{' + ', '.join(str(v) for v in row) + '},\n')
            o.write('};\n\n')
    try:
        c = curve_tables(load(mode, src, 'dmime.dll'))
    except (OSError, ValueError, subprocess.CalledProcessError, struct.error) as e:
        print('dmime.dll: %s; every curve shape is linear' % e, file=sys.stderr)
        c = None
    with open(os.path.join(out_dir, '_MsCurveTables.h'), 'w') as o:
        o.write(head % 'dmime.dll' + '#define DmMs_CURVE_TABLES %d\n\n' % (1 if c else 0))
        for name in ('LINEAR', 'SINE', 'LOG', 'EXP'):
            vals = c[name] if c else [i * 100 for i in range(193)]
            o.write('static const int16_t DmMs_CURVE_%s[193] = {%s};\n' % (name, ', '.join(str(v) for v in vals)))


main()
