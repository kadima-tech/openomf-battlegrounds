#!/usr/bin/env python3
"""Writes the dmusic synth's DLS2 filter tables header from the player's own game disc.

dmsynth.dll (DirectX 9.0b, Dec 2002) ships in the disc's DirectX/DirectX.cab. Its 2-pole
low-pass coefficients (K, B1, B2: 16 resonance rows by 89 cutoff columns, Q30) are Microsoft's
data, so they are read at build time rather than kept in this repository. Without the disc the
header disables the filter.

usage: dmsynth_filter_tables.py <out.h> (--iso Battlegrounds.iso | --dll dmsynth.dll)
"""
import os
import struct
import subprocess
import sys

TABLES = (('K', 0x774970E0), ('B1', 0x77494460), ('B2', 0x77495AA0))
IMAGE_BASE = 0x77480000


def dll_from_iso(iso):
    cab = subprocess.run(['bsdtar', '-xOf', iso, 'DirectX/DirectX.cab'], capture_output=True, check=True).stdout
    return subprocess.run(['bsdtar', '-xOf', '-', 'dmsynth.dll'], input=cab, capture_output=True, check=True).stdout


def tables(b):
    pe = struct.unpack_from('<I', b, 0x3c)[0]
    nsec = struct.unpack_from('<H', b, pe + 6)[0]
    optsz = struct.unpack_from('<H', b, pe + 20)[0]
    if struct.unpack_from('<I', b, pe + 24 + 28)[0] != IMAGE_BASE:
        raise ValueError('not the DirectX 9.0b dmsynth.dll')
    secs = [struct.unpack_from('<IIII', b, pe + 24 + optsz + i * 40 + 8) for i in range(nsec)]

    def read(addr, n):
        rva = addr - IMAGE_BASE
        for vsz, va, rsz, raw in secs:
            if va <= rva < va + max(vsz, rsz):
                return b[raw + rva - va:raw + rva - va + n]
        raise ValueError('address %x not mapped' % addr)

    out = {}
    for name, addr in TABLES:
        d = read(addr, 16 * 89 * 4)
        out[name] = [struct.unpack_from('<89i', d, r * 89 * 4) for r in range(16)]
    if out['K'][0][0] != 208823:
        raise ValueError('unexpected table contents')
    return out


def main():
    out, mode, src = sys.argv[1], sys.argv[2], sys.argv[3]
    try:
        b = dll_from_iso(src) if mode == '--iso' else open(src, 'rb').read()
        t = tables(b)
    except (OSError, ValueError, subprocess.CalledProcessError, struct.error) as e:
        print('dmsynth filter tables: %s; building without the DLS2 filter' % e, file=sys.stderr)
        t = None
    os.makedirs(os.path.dirname(out) or '.', exist_ok=True)
    with open(out, 'w') as f:
        f.write('// Generated by re/scripts/dmsynth_filter_tables.py from the game disc\'s dmsynth.dll.\n#pragma once\n#include <stdint.h>\n\n')
        f.write('#define DmMs_FILTER_TABLES %d\n\n' % (1 if t else 0))
        for name, _ in TABLES:
            f.write('static const int32_t DmMs_FILTER_%s[16][89] = {\n' % name)
            for row in (t[name] if t else [[0] * 89] * 16):
                f.write('\t{' + ', '.join(str(v) for v in row) + '},\n')
            f.write('};\n\n')


main()
