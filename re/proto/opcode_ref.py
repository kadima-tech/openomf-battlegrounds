"""Write re/opcodes.md: every opcode used by shipped VMC2, with frequency, layout and decompiled body."""
import collections
import glob
import os
import re
import sys

sys.path.insert(0, os.path.dirname(__file__))
import disasm
import vmc2

used = collections.Counter()
for f in sorted(glob.glob('vmc2/*/*.bin')):
    c = vmc2.vmc2(open(f, 'rb').read(), disasm.count_behaviors(open(f[:-4] + '.refs', 'rb').read()))
    for b in c['behaviors']:
        for m in b['methods']:
            if m:
                for _, op, _ in disasm.disasm(m['contents'])[0]:
                    used[op] += 1

src = open('dump/Core/functions/7014eaa0.c').read().split('\n')
start = next(i for i, l in enumerate(src) if 'switch(iVar41)' in l)
bodies, cur = {}, []
for line in src[start + 1:]:
    m = re.match(r'^        case (0x[0-9a-f]+|\d+):', line)
    if m:
        if cur and cur[-1][1]:
            pass
        cur.append((int(m.group(1), 0), []))
        continue
    if cur:
        cur[-1][1].append(line)
# Fallthrough labels share the next non-empty body.
pending = []
for op, body in cur:
    pending.append(op)
    if body:
        for o in pending:
            bodies[o] = body
        pending = []

with open('opcodes.md', 'w') as out:
    out.write('# DE VM opcodes used by shipped VMC2\n\n')
    out.write(f'{len(used)} opcodes, {sum(used.values())} instructions. Generated by `proto/opcode_ref.py`.\n\n')
    for op, n in sorted(used.items()):
        size, layout, jump = disasm.OPS[op]
        out.write(f'## {op} (0x{op:x}) — used {n}×, operands: {" ".join(layout) or "none"}{" (jump)" if jump else ""}\n\n```c\n')
        body = [l for l in bodies.get(op, []) if 'Section=' not in l]
        out.write('\n'.join(l[8:] for l in body[:60]).rstrip() + ('\n  ...' if len(body) > 60 else '') + '\n```\n\n')
print(len(used), 'opcodes,', sum(used.values()), 'instructions')
print(' '.join(f'{op}:{n}' for op, n in used.most_common(40)))
