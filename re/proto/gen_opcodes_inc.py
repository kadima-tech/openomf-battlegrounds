"""Generate engine/src/vm/opcodes.inc from the interpreter decompile (via opcodes.py)."""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
import opcodes

KIND = {'i32': 'kI32', 'dword': 'kU32', 'int': 'kI32', 'float': 'kF32', 'byte': 'kU8', 'char': 'kI8',
        'word': 'kU16', 'short': 'kI16', 'blob': 'kBlob', 'word?10': 'kU16IfClass'}
out = os.path.join(os.path.dirname(__file__), '../../engine/src/vm/opcodes.inc')
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, 'w') as f:
    f.write('// Generated by re/proto/gen_opcodes_inc.py from DE_CPCExecuter::ContinueExecutionInternal\n')
    f.write('// (Core 0x7014eaa0). OP(opcode, is_jump, operand kinds...)\n')
    for op in sorted(k for k in opcodes.TABLE if isinstance(k, int)):
        _, layout, jump = opcodes.TABLE[op]
        kinds = ', '.join(KIND[t] for t in layout)
        f.write(f'OP({op}, {"true" if jump else "false"}{", " + kinds if kinds else ""})\n')
print('wrote', out, len(opcodes.TABLE))
